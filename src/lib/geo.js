export function isValidZip(zip) {
  return typeof zip === 'string' && /^\d{5}$/.test(zip);
}

export function stateForZip(zip) {
  if (!isValidZip(zip)) return null;
  const zip3 = Number(zip.slice(0, 3));
  const range = ZIP3_RANGES.find(([lo, hi]) => zip3 >= lo && zip3 <= hi);
  return range ? range[2] : null;
}

export function haversineMiles(a, b) {
  const toRad = (d) => (d * Math.PI) / 180;
  const R = 3958.8;
  const dLat = toRad(b.lat - a.lat);
  const dLon = toRad(b.lon - a.lon);
  const h =
    Math.sin(dLat / 2) ** 2 +
    Math.cos(toRad(a.lat)) * Math.cos(toRad(b.lat)) * Math.sin(dLon / 2) ** 2;
  return 2 * R * Math.asin(Math.sqrt(h));
}
